// CONTRACT-NOTE: there is no equipment ID for an ab wheel, sled, battle ropes, pendulum squat,
//   belt squat, 45-degree hyperextension bench or plate-loaded biceps/triceps machines.
//   - Ab-wheel rollout is modelled as a barbell rollout (['barbell']); a DB rollout and a
//     towel/slider rollout give no-wheel options. Users with a wheel can pick either.
//   - The 45-degree back extension uses 'ghd' (the closest station ID; most gyms keep both).
//   - Hip adductor machine uses 'abductor_machine' (commercial gyms use the same combo unit).
//   - Assisted (machine) tricep dip uses 'assisted_pullup' (the combo assisted dip/chin machine).
//   - Sled push, pendulum and belt squat are omitted because they have no equipment ID.
// CONTRACT-NOTE: 'home'/'travel'/'office'/'gym' tags are derived from equipment against
//   DEFAULT_LOCATIONS (office = bodyweight only). Extra descriptive tags are set per exercise.

const HOME = new Set(['dumbbell', 'adjustable_bench', 'flat_bench', 'trap_bar', 'outdoors']);
const TRAVEL = new Set(['dumbbell', 'flat_bench', 'treadmill', 'bike', 'outdoors']);

const yt = q => 'https://www.youtube.com/results?search_query=' + encodeURIComponent(q + ' form').replace(/%20/g, '+');

function X(id, name, equipment, o) {
  const eq = equipment;
  const auto = [];
  if (eq.every(e => HOME.has(e))) auto.push('home');
  if (eq.every(e => TRAVEL.has(e))) auto.push('travel');
  if (eq.length === 0) auto.push('office');
  if (!(eq.length === 1 && eq[0] === 'trap_bar')) auto.push('gym');
  const { tags = [], ytq, ...rest } = o;
  return {
    id, name, equipment: eq,
    alt: [],
    category: 'isolation',
    emphasis: [],
    unit: 'each', step: 2.5, secPerRep: 3, setupSec: 30,
    unilateral: false, difficulty: 1, fatigue: 1,
    ...rest,
    yt: yt(ytq || name),
    tags: [...new Set([...auto, ...tags])],
  };
}

