const CACHE = 'forge-' + VERSION;   // this version's app files
const RUNTIME = 'forge-runtime';    // data and on-demand assets, kept across versions
const SCOPE = self.registration.scope;
const abs = p => new URL(p, SCOPE).href;
const APP = new Set(PRECACHE.map(abs));
const SHELL = abs('./index.html');

self.addEventListener('install', e => {
  // 'no-cache' revalidates with the server: unchanged files cost a 304, and a new version never picks up a stale
  // copy from the browser's HTTP cache. Data is best effort; the app opens without it.
  e.waitUntil((async () => {
    const app = await caches.open(CACHE);
    await app.addAll(PRECACHE.map(p => new Request(p, { cache: 'no-cache' })));
    const rt = await caches.open(RUNTIME);
    await Promise.all(PREFETCH.map(p => fetch(p, { cache: 'no-cache' }).then(r => r.ok && rt.put(abs(p), r)).catch(() => {})));
  })());
  // No skipWaiting here: a new version waits until the page asks for it or every Forge window has closed.
});

self.addEventListener('message', e => {
  if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(ks => Promise.all(ks.filter(k => k.startsWith('forge-') && k !== CACHE && k !== RUNTIME).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const u = new URL(req.url);
  if (u.origin !== location.origin) return;
  // Match without the query string so cache-busting params (?t=…) don't pile up entries.
  u.search = ''; u.hash = '';
  const key = u.href;
  if (req.mode === 'navigate' && (key === SCOPE || key === SHELL)) e.respondWith(appFile(SHELL, req));
  else if (APP.has(key)) e.respondWith(appFile(key, req));
  else e.respondWith(networkFirst(req, key));
});

async function appFile(key, req) {
  const app = await caches.open(CACHE);
  const hit = await app.match(key);
  if (hit) return hit;
  // Not cached (an install still running, or the browser evicted it): fetch and keep it.
  try {
    const res = await fetch(req);
    if (res.ok && !res.redirected) app.put(key, res.clone());
    return res;
  } catch (err) {
    return offline(req, key);
  }
}

async function networkFirst(req, key) {
  try {
    const res = await fetch(req);
    if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then(c => c.put(key, copy)); }
    return res;
  } catch (err) {
    return offline(req, key);
  }
}

async function offline(req, key) {
  const hit = await caches.match(key);
  if (hit) return hit;
  // A navigation to a URL we never cached (e.g. a deep link opened offline) still has to get the app shell, and
  // anything else must get a real Response: respondWith(undefined) surfaces as a network error the page can't
  // recover from.
  if (req.mode === 'navigate') {
    const shell = await caches.match(SHELL);
    if (shell) return shell;
  }
  return new Response('', { status: 504, statusText: 'Offline' });
}
